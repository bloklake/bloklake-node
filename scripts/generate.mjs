// Generates src/fields.ts from scripts/schema.json (a copy of `GET /v1/schema`).
// Run `npm run generate` after refreshing schema.json when the API adds fields.
import { readFileSync, writeFileSync } from "node:fs";

const schema = JSON.parse(readFileSync(new URL("./schema.json", import.meta.url), "utf8"));

/** uint256 amounts: 32 bytes like a hash, but decimal strings in JSON (the server's catalogue). */
const UINT256 = ["max_refund", "submission_fee_refund", "deposit_value", "retry_value", "max_submission_fee", "l1_base_fee"];

const ROW_TYPES = [
  { key: "logs", field: "LogField", row: "Log" },
  { key: "transactions", field: "TransactionField", row: "Transaction" },
  { key: "blocks", field: "BlockField", row: "Block" },
];

// ---- a tiny parser for the schema's Arrow type names ----------------------------------
function parseType(s) {
  let i = 0;
  const ws = () => { while (s[i] === " ") i++; };
  const ident = () => { const m = /^[A-Za-z0-9_]+/.exec(s.slice(i)); i += m[0].length; return m[0]; };
  function type() {
    ws();
    const name = ident();
    if (name === "FixedSizeBinary") { i++; const n = ident(); i++; return { kind: "fsb", width: Number(n) }; }
    if (name === "List") { i++; const t = type(); i++; return { kind: "list", item: t }; }
    if (name === "Struct") {
      i++; const fields = [];
      for (;;) { ws(); const n = ident(); ws(); i++; const t = type(); fields.push({ name: n, type: t }); ws(); if (s[i] === ",") { i++; continue; } i++; break; }
      return { kind: "struct", fields };
    }
    return { kind: "prim", name };
  }
  return type();
}

const structs = new Map(); // signature -> interface name
const STRUCT_NAMES = { withdrawals: "Withdrawal", access_list: "AccessListEntry", authorization_list: "Authorization" };

function tsType(t, column, top) {
  if (t.kind === "prim") return t.name.startsWith("UInt") ? "number" : t.name === "Binary" ? "string" : "unknown";
  if (t.kind === "fsb") return "string";
  if (t.kind === "list") return `${tsType(t.item, column, false)}[]`;
  const name = STRUCT_NAMES[column] ?? `${column}_entry`;
  if (!structs.has(name)) {
    structs.set(name, `export interface ${name} {\n${t.fields.map((f) => `  ${f.name}: ${tsType(f.type, f.name, false)};`).join("\n")}\n}`);
  }
  return name;
}

const doc = (f) => `${f.arrow_type}${f.family !== "base" ? `, ${f.family === "op_stack" ? "OP Stack" : "Arbitrum"} chains` : ""}`;

let out = `// Generated by scripts/generate.mjs from scripts/schema.json (GET /v1/schema). Do not edit.

`;
const parts = [];
for (const rt of ROW_TYPES) {
  const fields = schema.row_types[rt.key];
  const names = fields.map((f) => `"${f.dsl_name}"`);
  if (rt.key === "logs") names.push(`"topics"`);
  parts.push(`/** Field names for \`fields.${rt.key === "logs" ? "log" : rt.key === "transactions" ? "transaction" : "block"}\`. */
export type ${rt.field} =\n  | ${names.join("\n  | ")};
`);
  parts.push(`/** JSON type of each ${rt.key.slice(0, -1)} field, by request name. */
export interface ${rt.field}Types {
${fields.map((f) => `  /** ${doc(f)} */\n  ${f.dsl_name}: ${tsType(parseType(f.arrow_type), f.name, true)}${f.nullable ? " | null" : ""};`).join("\n")}
}
`);
  parts.push(`/** Column (response key) of each ${rt.key.slice(0, -1)} field, by request name. */
export interface ${rt.field}Columns {
${fields.map((f) => `  ${f.dsl_name}: "${f.name}";`).join("\n")}
}
`);
  parts.push(`/** A ${rt.key.slice(0, -1)} row with every field (each present only if selected). */
export interface ${rt.row} {
${fields.map((f) => `  ${f.name}?: ${tsType(parseType(f.arrow_type), f.name, true)}${f.nullable ? " | null" : ""};`).join("\n")}
}
`);
}
out += [...structs.values()].join("\n\n") + "\n\n" + parts.join("\n");
out += `
/** Response keys that hold uint256 amounts (decimal strings), per row type. */
export const UINT256_COLUMNS: Record<string, ReadonlySet<string>> = {
  transactions: new Set(${JSON.stringify(UINT256)}),
};
`;
writeFileSync(new URL("../src/fields.ts", import.meta.url), out);
console.log("wrote src/fields.ts");
